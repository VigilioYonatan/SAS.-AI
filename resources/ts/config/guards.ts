import { storageEmpresa } from "@/empresas/stores/empresa.store";
import { NOW, TimePeru, restarDays } from "~/libs/helpers";

// subscripciones
export interface Technologies {
	id: number;
	date: Date | null;
	enabled: boolean;
	tokens?: number;
	features?: {
		clientes_registrados: number;
		trabajadores_cantidad: number;
		products_total: number;
	};
}
const payments = storageEmpresa?.payments!;

export function mensual() {
	return (
		payments.mensual?.enabled &&
		restarDays(NOW().toDate(), TimePeru(payments.mensual?.date!).toDate()) >= 0
	);
}
export function subFacturacion() {
	return (
		payments.facturacion?.enabled &&
		restarDays(
			NOW().toDate(),
			TimePeru(payments.facturacion?.date!).toDate(),
		) >= 0
	);
}

