export interface Technologies {
    id: number;
    date: Date | null;
    enabled: boolean;
    tokens?: number;
    features?: {
        clientes_registrados: number;
        trabajadores_cantidad: number;
        products_total: number;
    };
}
const payments = storageInformation?.payments!;

export function subFacturacion() {
    return (
        payments.sunat.enabled &&
        restarDays(NOW().toDate(), TimePeru(payments.sunat.date!).toDate()) >= 0
    );
}
export function subWhatsappIA() {
    const information = useInformationstore().state!;
    return (
        payments.ia.enabled &&
        restarDays(NOW().toDate(), TimePeru(payments.ia.date!).toDate()) >= 0 &&
        payments.ia.tokens &&
        payments.ia.tokens >
            information.inteligenceArtificial.usage.input_tokens
    );
}

