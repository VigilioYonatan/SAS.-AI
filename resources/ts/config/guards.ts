import enviroments from ".";
import { useQuery } from "@vigilio/preact-fetching";
import useInformationstore, {
	storageInformation,
} from "@/information/stores/information.store";
import { NOW, TimePeru, restarDays } from "~/libs/helpers";

export function initiCategoriesSubcategories() {
	// 1 de restaurante y token
	return useQuery<CategoriesAllWebApi, unknown>(
		`/webs/${enviroments.VITE_VIGILIO_TOKEN}/all`,
		async (url) => {
			const response = await fetch(`${enviroments.VITE_VIGILIO_WEB}/api${url}`);
			const result = await response.json();

			if (!result.success) throw result;
			return result;
		},
	);
}

// subscripciones
export interface Technologies {
	id: number;
	date: Date | null;
	enabled: boolean;
	tokens?: number;
	features?: {
		clientes_registrados: number;
		trabajadores_cantidad: number;
		products_total: number;
	};
}
const technologies = storageInformation?.technologies!;

export function subFeatures() {
	return technologies.find((tech) => tech.id === 1);
}
export function subDominioH() {
	return technologies.some(
		(tech) =>
			tech.id === 2 &&
			restarDays(NOW().toDate(), TimePeru(tech.date!).toDate()) >= 0,
	);
}
export function subFacturacion() {
	return technologies.some(
		(tech) =>
			tech.id === 3 &&
			restarDays(NOW().toDate(), TimePeru(tech.date!).toDate()) >= 0,
	);
}
export function subWhatsappIA() {
	const information = useInformationstore().state!;
	return technologies.some(
		(tech) =>
			tech.id === 4 &&
			restarDays(NOW().toDate(), TimePeru(tech.date!).toDate()) >= 0 &&
			tech.tokens &&
			tech.tokens > information.inteligenceArtificial.usage.input_tokens,
	);
}

// web
export function webNormal() {
	return technologies.some((tech) => tech.id === 5 && tech.enabled);
}
export function webStandard() {
	return technologies.some((tech) => tech.id === 6 && tech.enabled);
}
export function webEmpresarial() {
	return technologies.some((tech) => tech.id === 7 && tech.enabled);
}
